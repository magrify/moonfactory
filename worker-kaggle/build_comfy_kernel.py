"""Build worker-kaggle/comfy_worker_kernel.py from its template.

The platform pushes the generated file to Kaggle verbatim (the
same pattern as hf_worker_kernel.py), so everything the kernel
needs rides inside the one script: the workflow templates from
workflows/, the model manifest from comfy_model_manifest.json,
and the Modal worker's own literals (the effects table, the
lane dimensions, the negative prompt), extracted from
modal-worker/app.py by AST so the two workers can never drift
on the data they share. The builders themselves are carried
over in the template and pinned against the Modal worker's by
scratch/check_kaggle_comfy.py.

Run:  python3 worker-kaggle/build_comfy_kernel.py
"""

import ast
import json
from pathlib import Path

ROOT = Path(__file__).parent.parent
TEMPLATE = Path(__file__).parent / "comfy_kernel_template.py"
MANIFEST = Path(__file__).parent / "comfy_model_manifest.json"
OUT = Path(__file__).parent / "comfy_worker_kernel.py"

WORKFLOW_FILES = (
    "draft_i2v_5b.json",
    "prod_i2v_a14b.json",
    "prod_i2v_a14b_distilled.json",
    "firstlast_chain.json",
    "fun_camera_i2v.json",
    "effects_i2v.json",
    "z_image_t2i.json",
    "flux2_klein_t2i.json",
    "krea2_verite_t2i.json",
    "hunyuan15_t2v.json",
    "hunyuan15_i2v.json",
    "longcat_t2i.json",
    "wan_animate.json",
)


def literal(tree, name):
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == name
                for t in node.targets):
            return ast.literal_eval(node.value)
    raise AssertionError(f"{name} not found at module level")


def main():
    worker_tree = ast.parse(
        (ROOT / "modal-worker" / "app.py").read_text())
    templates = {
        name: json.loads((ROOT / "workflows" / name).read_text())
        for name in WORKFLOW_FILES
    }
    effects = literal(worker_tree, "EFFECTS")
    payload = {
        "__TEMPLATES_JSON__": json.dumps(templates),
        "__MANIFEST_JSON__": MANIFEST.read_text().strip(),
        "__EFFECTS_JSON__": json.dumps(effects),
        "__LANE_DIMS_JSON__": json.dumps(literal(worker_tree, "LANE_DIMS")),
        "__EFFECTS_DIMS_JSON__": json.dumps(
            literal(worker_tree, "EFFECTS_DIMS")),
        "__IMAGE_DIMS_JSON__": json.dumps(literal(worker_tree, "IMAGE_DIMS")),
        "__POSES_JSON__": json.dumps(literal(worker_tree, "FUN_CAMERA_POSES")),
        "__NEGATIVE_JSON__": json.dumps(
            literal(worker_tree, "NEGATIVE_PROMPT")),
    }
    text = TEMPLATE.read_text()
    for marker, value in payload.items():
        if marker not in text:
            raise AssertionError(f"marker {marker} missing from template")
        # The template reads each payload with json.loads over a
        # raw triple-quoted string, so the JSON must arrive
        # byte for byte; the one sequence that could break the
        # string literal is a triple quote, which JSON text of
        # this shape never contains.
        if "'''" in value:
            raise AssertionError(f"payload for {marker} contains a "
                                 "triple quote")
        text = text.replace(marker, value)
    header = ("# GENERATED by worker-kaggle/build_comfy_kernel.py "
              "from comfy_kernel_template.py.\n"
              "# Do not edit this file; edit the template and rebuild.\n")
    OUT.write_text(header + text)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
